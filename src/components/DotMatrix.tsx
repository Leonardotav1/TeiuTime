const UNIT = 1.06

export function DotMatrix({ text, className, dim }: { text: string; className?: string; dim?: boolean }) {
  const dots: { x: number; y: number }[] = []
  let cursor = 0
  for (const ch of text) {
    const glyph = GLYPHS[ch]
    if (!glyph) {
      cursor += UNIT * 6
      continue
    }
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === '1') dots.push({ x: cursor + x * UNIT, y: y * UNIT })
      }
    })
    cursor += 5 * UNIT + UNIT * 0.9
  }
  const w = cursor - UNIT * 0.9
  return (
    <svg
      className={className}
      viewBox={`0 0 ${w} ${7 * UNIT}`}
      role="img"
      aria-hidden="true"
      style={dim ? { opacity: 0.18 } : undefined}
    >
      {dots.map((d, i) => (
        <circle key={i} cx={d.x} cy={d.y} r={0.46} className="dm-dot" />
      ))}
    </svg>
  )
}